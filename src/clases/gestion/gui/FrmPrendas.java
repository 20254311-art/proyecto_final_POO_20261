    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigo = txtCodigo.getText();

        Prenda encontrada = gestion.buscarPrenda(codigo);

        if (encontrada != null) {

            codigoOriginal = encontrada.getCodigo();

            txtCodigo.setText(encontrada.getCodigo());
            txtNombre.setText(encontrada.getNombre());
            txtTela.setText(encontrada.getTelaPrincipal());

            txtConsumoS.setText(String.valueOf(encontrada.getConsumoS()));
            txtConsumoM.setText(String.valueOf(encontrada.getConsumoM()));
            txtConsumoL.setText(String.valueOf(encontrada.getConsumoL()));
            txtConsumoXL.setText(String.valueOf(encontrada.getConsumoXL()));

            txtTiempo.setText(String.valueOf(encontrada.getTiempoConfeccion()));
            txtPrecio.setText(String.valueOf(encontrada.getPrecioVenta()));

            txtCostoMetro.setText(String.valueOf(encontrada.getCostoMetroTela()));
            txtCostoCostura.setText(String.valueOf(encontrada.getCostoCostura()));

            cmbEstado.setSelectedItem(encontrada.getEstado());

            if (encontrada instanceof Polo) {

                cmbTipo.setSelectedItem("Polo");

                txtCostoLavado.setText("");
                txtCostoForro.setText("");
                txtCostoAvios.setText("");

            } else if (encontrada instanceof Jean) {

                cmbTipo.setSelectedItem("Jean");

                Jean jean = (Jean) encontrada;

                txtCostoLavado.setText(String.valueOf(jean.getCostoLavado()));

                txtCostoForro.setText("");
                txtCostoAvios.setText("");

            } else if (encontrada instanceof Casaca) {

                cmbTipo.setSelectedItem("Casaca");

                Casaca casaca = (Casaca) encontrada;

                txtCostoForro.setText(String.valueOf(casaca.getCostoForro()));
                txtCostoAvios.setText(String.valueOf(casaca.getCostoAvisos()));

                txtCostoLavado.setText("");
            }

            configurarCamposPorTipo();

            javax.swing.JOptionPane.showMessageDialog(this,"Prenda encontrada correctamente.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ninguna prenda con ese código.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (!validarDatos()) {
            return;
        }
        
        if (codigoOriginal == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debes buscar una prenda.");
            return;
        }

        try {

            String codigo = txtCodigo.getText();
            String nombre = txtNombre.getText();
            String tipo = cmbTipo.getSelectedItem().toString();
            String tela = txtTela.getText();
            String estado = cmbEstado.getSelectedItem().toString();

            double consumoS = Double.parseDouble(txtConsumoS.getText());
            double consumoM = Double.parseDouble(txtConsumoM.getText());
            double consumoL = Double.parseDouble(txtConsumoL.getText());
            double consumoXL = Double.parseDouble(txtConsumoXL.getText());

            double tiempo = Double.parseDouble(txtTiempo.getText());
            double precio = Double.parseDouble(txtPrecio.getText());
            double costoMetro = Double.parseDouble(txtCostoMetro.getText());
            double costoCostura = Double.parseDouble(txtCostoCostura.getText());

            Prenda actualizada = null;

            if (tipo.equals("Polo")) {

                actualizada = new Polo(codigo, nombre, tela,consumoS, consumoM, consumoL, consumoXL,
                        tiempo, precio, estado,
                        costoMetro, costoCostura);

            } else if (tipo.equals("Jean")) {

                double lavado = Double.parseDouble(txtCostoLavado.getText());

                actualizada = new Jean(
                        lavado, codigo, nombre, tela,
                        consumoS, consumoM, consumoL, consumoXL,
                        tiempo, precio, estado,
                        costoMetro, costoCostura);

            } else if (tipo.equals("Casaca")) {

                double forro = Double.parseDouble(txtCostoForro.getText());
                double avios = Double.parseDouble(txtCostoAvios.getText());

                actualizada = new Casaca(forro, avios, codigo, nombre, tela, consumoS, consumoM, consumoL, consumoXL,
                        tiempo, precio, estado,
                        costoMetro, costoCostura);
            }

            if (gestion.modificarPrenda(codigoOriginal, actualizada)) {
                DefaultTableModel modelo =
                        (DefaultTableModel) tblPrendas.getModel();

                for (int i = 0; i < modelo.getRowCount(); i++) {
                    if (modelo.getValueAt(i, 0).toString().equals(codigoOriginal)) {

                        modelo.setValueAt(codigo, i, 0);
                        modelo.setValueAt(nombre, i, 1);
                        modelo.setValueAt(tipo, i, 2);
                        modelo.setValueAt(tela, i, 3);
                        modelo.setValueAt(precio, i, 4);
                        modelo.setValueAt(estado, i, 5);

                        break;
                    }
                }

                codigoOriginal = codigo;

                javax.swing.JOptionPane.showMessageDialog(this, "Prenda modificada correctamente.");

            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo modificar. Verifica el código y el tipo de prenda.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Verifica los campos numéricos.");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String codigo = codigoOriginal;

        if (codigo == null || codigo.isEmpty()) {
            codigo = txtCodigo.getText();
        }

        if (codigo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debes buscar una prenda.");
            return;
        }

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Estás seguro de eliminar esta prenda?",
                "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
            if (gestion.eliminarPrenda(codigo)) {
                DefaultTableModel modelo =
                        (DefaultTableModel) tblPrendas.getModel();

                for (int i = 0; i < modelo.getRowCount(); i++) {
                    if (modelo.getValueAt(i, 0).toString().equals(codigo)) {
                        modelo.removeRow(i);
                        break;
                    }
                }

                codigoOriginal = null;

                javax.swing.JOptionPane.showMessageDialog(this, "Prenda eliminada correctamente.");

            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se encontró la prenda.");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

