    private boolean validarDatos() {

    if (txtCodigo.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty() || txtTela.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Completa todos los datos generales.");
        return false;
    }

    try {

        double consumoS = Double.parseDouble(txtConsumoS.getText());
        double consumoM = Double.parseDouble(txtConsumoM.getText());
        double consumoL = Double.parseDouble(txtConsumoL.getText());
        double consumoXL = Double.parseDouble(txtConsumoXL.getText());

        double tiempo = Double.parseDouble(txtTiempo.getText());
        double precio = Double.parseDouble(txtPrecio.getText());
        double costoMetro = Double.parseDouble(txtCostoMetro.getText());
        double costoCostura = Double.parseDouble(txtCostoCostura.getText());

        if (consumoS <= 0 || consumoM <= 0 || consumoL <= 0 || consumoXL <= 0 || tiempo <= 0 || precio <= 0 
                || costoMetro <= 0 || costoCostura <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los valores numéricos deben ser mayores que cero.");
            return false;
        }

        String tipo = cmbTipo.getSelectedItem().toString();

        if (tipo.equals("Jean")) {

            double lavado = Double.parseDouble(txtCostoLavado.getText());

            if (lavado < 0) {
                javax.swing.JOptionPane.showMessageDialog(this,"El costo de lavado no puede ser negativo.");
                return false;
            }

        } else if (tipo.equals("Casaca")) {

            double forro = Double.parseDouble(txtCostoForro.getText());
            double avios = Double.parseDouble(txtCostoAvios.getText());

            if (forro < 0 || avios < 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Los costos de forro y avíos no pueden ser negativos.");
                return false;
            }
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(this,"Verifica que todos los campos numéricos contengan valores válidos.");
        return false;
    }

    return true;
}
    
