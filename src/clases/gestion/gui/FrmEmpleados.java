    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String DNI = txtDNI.getText().trim();
        if (DNI.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el DNI del empleado.");
        }else{
            Empleado encontrado = gestion.buscarEmpleado(DNI);
            if (encontrado != null){
                
                dniOriginal = encontrado.getDNI();
                
                txtNombres.setText(encontrado.getNombres());
                txtApellidos.setText(encontrado.getApellidos());
                txtUsuario.setText(encontrado.getUsuario());
                txtClave.setText(encontrado.getClave());
                cmbRol.setSelectedItem(encontrado.getRol());
                
                javax.swing.JOptionPane.showMessageDialog(this, "Empleado encontrado correctamente.");
                
            }else{
                javax.swing.JOptionPane.showMessageDialog(this, "No se encontro ningun empleado con ese DNI.");
            }
            
        }
        
        
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (dniOriginal == null){
            javax.swing.JOptionPane.showMessageDialog(this,
            "Primero busque un empleado.");
            return;
        }
        
        String DNI = txtDNI.getText().trim();
        String nombres = txtNombres.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String clave = new String(txtClave.getPassword());
        String rol = cmbRol.getSelectedItem().toString();
        
        if (DNI.isEmpty() || nombres.isEmpty() || apellidos.isEmpty()
        || usuario.isEmpty() || clave.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this,
            "Complete todos los campos.");
            return;
        }
        
        Empleado actualizado = new Empleado(DNI, nombres, apellidos, usuario, clave, rol);
        
        if (gestion.modificarEmpleados(dniOriginal, actualizado)){
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblEmpleados.getModel();
            
            for (int i = 0; i < modelo.getRowCount(); i++) {
                if (modelo.getValueAt(i, 0) != null && modelo.getValueAt(i, 0).toString().equals(dniOriginal)) {
                    modelo.setValueAt(DNI, i, 0);
                    modelo.setValueAt(nombres, i, 1);
                    modelo.setValueAt(apellidos, i, 2);
                    modelo.setValueAt(usuario, i, 3);
                    modelo.setValueAt(rol, i, 4);
                    break;
                }
            }
            
            dniOriginal = DNI;
            
            javax.swing.JOptionPane.showMessageDialog(this, "Empleado modificado correctamente.");
        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo modificar. Verifique los datos.");
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String DNI = txtDNI.getText().trim();
        if (DNI.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el DNI del empleado.");
            return;
        }
        
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this, "¿Desea eliminar este empleado?", 
                "Confirmar eliminación", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (respuesta == javax.swing.JOptionPane.YES_OPTION){
            if (respuesta == javax.swing.JOptionPane.YES_OPTION){
                javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblEmpleados.getModel();
                for (int i = 0; i < modelo.getRowCount(); i++) {
                    if (modelo.getValueAt(i, 0) != null && modelo.getValueAt(i, 0).toString().equals(DNI)) {
                        modelo.removeRow(i);
                        break;
                    }
                }
                
                dniOriginal = null;
                javax.swing.JOptionPane.showMessageDialog(this, "Empleado eliminado correctamente.");
            }else{
                javax.swing.JOptionPane.showMessageDialog(this, "Empleado no encontrado.");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

