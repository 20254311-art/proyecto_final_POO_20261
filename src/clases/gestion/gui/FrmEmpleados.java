    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String DNI  = txtDNI.getText().trim();
        String nombres = txtNombres.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String clave = new String(txtClave.getPassword());
        String rol = cmbRol.getSelectedItem().toString();
        
        if (DNI.isEmpty() || nombres.isEmpty() || apellidos.isEmpty() || usuario.isEmpty() || clave.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this,"Complete todos los campos.");
        }else{
            Empleado nuevo = new Empleado(DNI, nombres, apellidos, usuario, clave, rol);
            if(gestion.registrarEmpleado(nuevo)){
                javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblEmpleados.getModel();
                modelo.addRow(new Object[]{ DNI, nombres, apellidos, usuario, rol});
                javax.swing.JOptionPane.showMessageDialog(this, "Empleado registrado correctamente.");
            }else{
                javax.swing.JOptionPane.showMessageDialog(this, "El DNI o usuario ya existe, o el arreglo esta lleno.");
            }
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

